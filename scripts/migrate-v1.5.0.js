const { Client } = require('pg');
require('dotenv').config();

const {
  construirConfiguracion,
  validarConfiguracion,
} = require('./db-config');

// Migración incremental de v1.5.0: agrega la traza de entregas de la
// mensajería asíncrona. No borra ni recrea las tablas existentes.
const SQL = `
DO $$
BEGIN
  CREATE TYPE canal_notificacion AS ENUM ('CORREO', 'PUSH', 'SMS');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
  CREATE TYPE estado_entrega AS ENUM ('PENDIENTE', 'ENVIADA', 'SIMULADA', 'FALLIDA');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS entregas_notificacion (
  id_entrega BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_notificacion INTEGER NOT NULL,
  canal canal_notificacion NOT NULL DEFAULT 'CORREO',
  destinatario VARCHAR(150),
  estado estado_entrega NOT NULL DEFAULT 'PENDIENTE',
  intento INTEGER NOT NULL DEFAULT 1,
  detalle TEXT,
  fecha_entrega TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_entrega_notificacion FOREIGN KEY (id_notificacion)
    REFERENCES notificaciones (id_notificacion)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT uq_entrega_notificacion_canal UNIQUE (id_notificacion, canal)
);

CREATE INDEX IF NOT EXISTS idx_entregas_notificacion
  ON entregas_notificacion (id_notificacion);

CREATE INDEX IF NOT EXISTS idx_entregas_estado
  ON entregas_notificacion (estado);
`;

const ejecutar = async () => {
  validarConfiguracion();

  const client = new Client(construirConfiguracion());
  await client.connect();

  try {
    await client.query(SQL);

    const { rows } = await client.query(`
      SELECT COUNT(*)::int AS entregas
      FROM entregas_notificacion
    `);

    console.log('Migración v1.5.0 aplicada correctamente.');
    console.log(`Tabla entregas_notificacion: ${rows[0].entregas} filas.`);
  } finally {
    await client.end();
  }
};

ejecutar().catch((error) => {
  console.error('Error al aplicar la migración v1.5.0:', error.message);
  process.exit(1);
});
