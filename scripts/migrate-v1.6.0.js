// ============================================================
// Migración incremental de v1.6.0: RAG y agente de IA.
//
// Agrega las tablas documentos_rag, fragmentos_rag e
// interacciones_agente, con búsqueda de texto en español y
// soporte opcional de pgvector.
//
// Uso: npm run db:migrate:agente
// ============================================================

const { Client } = require('pg');
require('dotenv').config();

const {
  construirConfiguracion,
  validarConfiguracion,
} = require('./db-config');

const SQL = `
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS documentos_rag (
  id_documento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(200) NOT NULL,
  fuente VARCHAR(255) NOT NULL,
  categoria VARCHAR(50) NOT NULL DEFAULT 'general',
  contenido TEXT NOT NULL,
  hash VARCHAR(64) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fragmentos_rag (
  id_fragmento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_documento BIGINT NOT NULL,
  orden INTEGER NOT NULL,
  contenido TEXT NOT NULL,
  embedding vector(1024),
  busqueda tsvector GENERATED ALWAYS AS (to_tsvector('spanish', contenido)) STORED,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_fragmento_documento FOREIGN KEY (id_documento)
    REFERENCES documentos_rag (id_documento)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT uq_fragmento_orden UNIQUE (id_documento, orden)
);

CREATE INDEX IF NOT EXISTS idx_fragmentos_rag_busqueda
  ON fragmentos_rag USING gin (busqueda);
CREATE INDEX IF NOT EXISTS idx_fragmentos_rag_embedding
  ON fragmentos_rag USING hnsw (embedding vector_cosine_ops);

CREATE TABLE IF NOT EXISTS interacciones_agente (
  id_interaccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INTEGER,
  pregunta TEXT NOT NULL,
  respuesta TEXT,
  fuentes JSONB NOT NULL DEFAULT '[]'::jsonb,
  modelo VARCHAR(100),
  proveedor VARCHAR(30),
  tokens_prompt INTEGER,
  tokens_respuesta INTEGER,
  latencia_ms INTEGER,
  estado VARCHAR(20) NOT NULL DEFAULT 'OK',
  error TEXT,
  direccion_ip VARCHAR(45),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_interaccion_usuario FOREIGN KEY (id_usuario)
    REFERENCES usuarios (id_usuario) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_interacciones_agente_usuario
  ON interacciones_agente (id_usuario);
CREATE INDEX IF NOT EXISTS idx_interacciones_agente_fecha
  ON interacciones_agente (created_at);
`;

const ejecutar = async () => {
  validarConfiguracion();

  const client = new Client(construirConfiguracion());
  await client.connect();

  try {
    await client.query(SQL);

    const { rows } = await client.query(`
      SELECT
        (SELECT COUNT(*) FROM documentos_rag)::int AS documentos,
        (SELECT COUNT(*) FROM fragmentos_rag)::int AS fragmentos,
        (SELECT COUNT(*) FROM interacciones_agente)::int AS interacciones
    `);

    console.log('Migración v1.6.0 aplicada correctamente.');
    console.log(
      `Documentos: ${rows[0].documentos} | Fragmentos: ${rows[0].fragmentos} | ` +
        `Interacciones: ${rows[0].interacciones}`
    );
  } finally {
    await client.end();
  }
};

ejecutar().catch((error) => {
  console.error('Error al aplicar la migración v1.6.0:', error.message);
  process.exit(1);
});
