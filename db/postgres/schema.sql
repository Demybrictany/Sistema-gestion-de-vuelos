-- ------------------------------------------------------------
-- Trigger para replicar "ON UPDATE CURRENT_TIMESTAMP" de MySQL
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ------------------------------------------------------------
-- roles
-- ------------------------------------------------------------
CREATE TABLE roles (
  id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE,
  descripcion VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- usuarios
-- ------------------------------------------------------------
CREATE TABLE usuarios (
  id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_rol INTEGER NOT NULL,
  nombre_usuario VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  nombres VARCHAR(100) NOT NULL,
  apellidos VARCHAR(100) NOT NULL,
  correo VARCHAR(150) UNIQUE,
  telefono VARCHAR(30),
  estado estado_activo NOT NULL DEFAULT 'ACTIVO',
  ultimo_acceso TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol)
    REFERENCES roles (id_rol) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE INDEX fk_usuario_rol_idx ON usuarios (id_rol);

-- ------------------------------------------------------------
-- aeropuertos
-- ------------------------------------------------------------
CREATE TABLE aeropuertos (
  id_aeropuerto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_iata CHAR(3) NOT NULL UNIQUE,
  nombre VARCHAR(150) NOT NULL,
  ciudad VARCHAR(100) NOT NULL,
  pais VARCHAR(100) NOT NULL,
  estado estado_activo NOT NULL DEFAULT 'ACTIVO',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- pasajeros
-- ------------------------------------------------------------
CREATE TABLE pasajeros (
  id_pasajero INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres VARCHAR(100) NOT NULL,
  apellidos VARCHAR(100) NOT NULL,
  fecha_nacimiento DATE,
  nacionalidad VARCHAR(80),
  pasaporte VARCHAR(50) NOT NULL UNIQUE,
  correo VARCHAR(150),
  telefono VARCHAR(30),
  estado estado_activo NOT NULL DEFAULT 'ACTIVO',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- puertas (25 puertas de embarque)
-- ------------------------------------------------------------
CREATE TABLE puertas (
  id_puerta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR(10) NOT NULL UNIQUE,
  zona VARCHAR(50),
  estado estado_puerta_banda NOT NULL DEFAULT 'DISPONIBLE',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- bandas_equipaje
-- ------------------------------------------------------------
CREATE TABLE bandas_equipaje (
  id_banda INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR(10) NOT NULL UNIQUE,
  zona VARCHAR(50),
  estado estado_puerta_banda NOT NULL DEFAULT 'DISPONIBLE',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- vuelos
-- ------------------------------------------------------------
CREATE TABLE vuelos (
  id_vuelo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_vuelo VARCHAR(20) NOT NULL,
  id_aeropuerto_origen INTEGER NOT NULL,
  id_aeropuerto_destino INTEGER NOT NULL,
  fecha_salida DATE NOT NULL,
  hora_salida TIME NOT NULL,
  fecha_llegada DATE NOT NULL,
  hora_llegada TIME NOT NULL,
  id_puerta INTEGER,
  estado estado_vuelo NOT NULL DEFAULT 'PROGRAMADO',
  motivo_cancelacion VARCHAR(255),
  capacidad_pasajeros INTEGER NOT NULL DEFAULT 0,
  observaciones TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_vuelo_origen FOREIGN KEY (id_aeropuerto_origen)
    REFERENCES aeropuertos (id_aeropuerto) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_vuelo_destino FOREIGN KEY (id_aeropuerto_destino)
    REFERENCES aeropuertos (id_aeropuerto) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_vuelo_puerta FOREIGN KEY (id_puerta)
    REFERENCES puertas (id_puerta) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT chk_vuelo_capacidad CHECK (capacidad_pasajeros >= 0),
  CONSTRAINT chk_vuelo_fechas CHECK (
    (fecha_llegada + hora_llegada) > (fecha_salida + hora_salida)
  )
);

CREATE INDEX fk_vuelo_origen_idx ON vuelos (id_aeropuerto_origen);
CREATE INDEX fk_vuelo_destino_idx ON vuelos (id_aeropuerto_destino);
CREATE INDEX fk_vuelo_puerta_idx ON vuelos (id_puerta);
CREATE INDEX idx_vuelos_fecha_salida ON vuelos (fecha_salida);
CREATE INDEX idx_vuelos_estado ON vuelos (estado);
CREATE INDEX idx_vuelos_codigo ON vuelos (codigo_vuelo);

-- ------------------------------------------------------------
-- itinerarios
-- ------------------------------------------------------------
CREATE TABLE itinerarios (
  id_itinerario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
