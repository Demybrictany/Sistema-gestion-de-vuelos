CREATE INDEX fk_itinerario_pasajero_idx ON itinerarios (id_pasajero);
CREATE INDEX fk_itinerario_origen_idx ON itinerarios (origen_principal);
CREATE INDEX fk_itinerario_destino_idx ON itinerarios (destino_final);

-- ------------------------------------------------------------
-- pasajero_vuelo
-- ------------------------------------------------------------
CREATE TABLE pasajero_vuelo (
  id_pasajero_vuelo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pasajero INTEGER NOT NULL,
  id_vuelo INTEGER NOT NULL,
  id_itinerario INTEGER,
  numero_asiento VARCHAR(10),
  estado estado_pasajero_vuelo NOT NULL DEFAULT 'RESERVADO',
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
  registrado_por INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_pasajero_vuelo UNIQUE (id_pasajero, id_vuelo),
  CONSTRAINT fk_pv_pasajero FOREIGN KEY (id_pasajero)
    REFERENCES pasajeros (id_pasajero) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_pv_vuelo FOREIGN KEY (id_vuelo)
    REFERENCES vuelos (id_vuelo) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_pv_itinerario FOREIGN KEY (id_itinerario)
    REFERENCES itinerarios (id_itinerario) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_pv_usuario FOREIGN KEY (registrado_por)
    REFERENCES usuarios (id_usuario) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE INDEX fk_pv_itinerario_idx ON pasajero_vuelo (id_itinerario);
CREATE INDEX fk_pv_usuario_idx ON pasajero_vuelo (registrado_por);
CREATE INDEX idx_pasajero_vuelo_vuelo ON pasajero_vuelo (id_vuelo);

-- ------------------------------------------------------------
-- escalas
-- ------------------------------------------------------------
CREATE TABLE escalas (
  id_escala INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_itinerario INTEGER NOT NULL,
  id_vuelo INTEGER NOT NULL,
  numero_escala INTEGER NOT NULL,
  aeropuerto_llegada INTEGER NOT NULL,
  aeropuerto_salida INTEGER NOT NULL,
  hora_llegada TIMESTAMPTZ NOT NULL,
  hora_salida TIMESTAMPTZ,
  id_puerta_llegada INTEGER,
  id_puerta_salida INTEGER,
  estado estado_escala NOT NULL DEFAULT 'PENDIENTE',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_itinerario_escala UNIQUE (id_itinerario, numero_escala),
  CONSTRAINT fk_escala_itinerario FOREIGN KEY (id_itinerario)
    REFERENCES itinerarios (id_itinerario) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_escala_vuelo FOREIGN KEY (id_vuelo)
    REFERENCES vuelos (id_vuelo) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_escala_aeropuerto_llegada FOREIGN KEY (aeropuerto_llegada)
    REFERENCES aeropuertos (id_aeropuerto) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_escala_aeropuerto_salida FOREIGN KEY (aeropuerto_salida)
    REFERENCES aeropuertos (id_aeropuerto) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_escala_puerta_llegada FOREIGN KEY (id_puerta_llegada)
    REFERENCES puertas (id_puerta) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_escala_puerta_salida FOREIGN KEY (id_puerta_salida)
    REFERENCES puertas (id_puerta) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE INDEX fk_escala_vuelo_idx ON escalas (id_vuelo);
CREATE INDEX fk_escala_aeropuerto_llegada_idx ON escalas (aeropuerto_llegada);
CREATE INDEX fk_escala_aeropuerto_salida_idx ON escalas (aeropuerto_salida);
CREATE INDEX fk_escala_puerta_llegada_idx ON escalas (id_puerta_llegada);
CREATE INDEX fk_escala_puerta_salida_idx ON escalas (id_puerta_salida);

-- ------------------------------------------------------------
-- equipajes
-- ------------------------------------------------------------
CREATE TABLE equipajes (
  id_equipaje INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_equipaje VARCHAR(50) NOT NULL UNIQUE,
  id_pasajero INTEGER NOT NULL,
  peso NUMERIC(6, 2),
  origen INTEGER NOT NULL,
  destino_final INTEGER NOT NULL,
  id_banda_actual INTEGER,
  estado estado_equipaje NOT NULL DEFAULT 'REGISTRADO',
  observaciones TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_equipaje_pasajero FOREIGN KEY (id_pasajero)
    REFERENCES pasajeros (id_pasajero) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_equipaje_origen FOREIGN KEY (origen)
    REFERENCES aeropuertos (id_aeropuerto) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_equipaje_destino FOREIGN KEY (destino_final)
    REFERENCES aeropuertos (id_aeropuerto) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_equipaje_banda FOREIGN KEY (id_banda_actual)
    REFERENCES bandas_equipaje (id_banda) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT chk_equipaje_peso CHECK (peso IS NULL OR peso >= 0)
);

CREATE INDEX fk_equipaje_origen_idx ON equipajes (origen);
CREATE INDEX fk_equipaje_destino_idx ON equipajes (destino_final);
CREATE INDEX fk_equipaje_banda_idx ON equipajes (id_banda_actual);
CREATE INDEX idx_equipaje_pasajero ON equipajes (id_pasajero);
CREATE INDEX idx_equipaje_estado ON equipajes (estado);

-- ------------------------------------------------------------
-- equipaje_vuelo (tramos del equipaje)
-- ------------------------------------------------------------
CREATE TABLE equipaje_vuelo (
  id_equipaje_vuelo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
